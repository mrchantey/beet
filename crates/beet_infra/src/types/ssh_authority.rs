//! The ssh certificate authority a stack's boxes trust, as a render reads it.
//!
//! A box admits no list of device keys. Its sshd trusts one user certificate
//! authority, so a login is a certificate that authority signed minutes ago,
//! and it answers with a host key its host certificate authority signed, so a
//! deploy verifies the box rather than trusting whatever answers at its
//! address. Both authorities are ed25519 keys in the stack's secret store,
//! minted by `<EnsureSshAuthority/>` before the apply that boots a box.
//!
//! One authority per stack rather than per repo: the secret store is scoped
//! per stack, so a stage's authority lives and is sealed beside the rest of
//! its secrets, a drill or dev stage can never sign its way into production,
//! and rolling one replaces that stack's boxes alone.
//!
//! This half is data and cloud-init text, compiled into every build that
//! describes infrastructure; the minting, signing and connecting are the
//! deploy's (`SshAuthority::ensure`, `SshConnection`).
use crate::prelude::*;
use beet_core::prelude::*;

/// A stack's ssh certificate authority, by the secrets that hold it: a user
/// authority signing every login and a host authority signing every box's
/// host key, each stored with its public half beside it.
///
/// The public halves are stored rather than re-derived for the same reason a
/// DKIM key's is: a render reads what it needs without reading the private key
/// that produced it.
#[derive(Debug, Clone, Copy, Default)]
pub struct SshAuthority;

impl SshAuthority {
	/// The login every box's certificates name, ie the account a deploy signs
	/// in as on an Amazon Linux box.
	pub const EC2_USER: &'static str = "ec2-user";

	/// The user authority's private key, OpenSSH encoded.
	pub fn user_ca() -> SecretRef { SecretRef::new("ssh-user-ca") }

	/// The user authority's public half, one `ssh-ed25519 ..` line: what a
	/// box's `TrustedUserCAKeys` holds.
	pub fn user_ca_public() -> SecretRef {
		SecretRef::new("ssh-user-ca-public")
	}

	/// The host authority's private key, OpenSSH encoded.
	pub fn host_ca() -> SecretRef { SecretRef::new("ssh-host-ca") }

	/// The host authority's public half: what a connection's known hosts
	/// trust as `@cert-authority`.
	pub fn host_ca_public() -> SecretRef {
		SecretRef::new("ssh-host-ca-public")
	}

	/// The tofu variable the user authority's public half arrives as, read
	/// from the store by every verb that renders.
	///
	/// Content, never defaulted: a box trusting an empty authority admits no
	/// one, and the only way back in is a rebuild.
	pub fn user_ca_variable() -> Variable {
		Variable::secret(Self::USER_CA_VARIABLE, Self::user_ca_public())
	}

	const USER_CA_VARIABLE: &'static str = "ssh_user_ca";

	/// Declare [`user_ca_variable`](Self::user_ca_variable) in `config`, once
	/// however many of the stack's boxes read it.
	pub fn declare_variable(config: &mut terra::Config) {
		let variable = Self::user_ca_variable();
		config.ensure_variable(
			variable.key().as_str(),
			variable.tf_declaration(),
		);
	}

	/// The token a [`trust_stanza`](SshHost::trust_stanza) holds where the
	/// user authority lands, so a `user_data` escaping every literal `${`
	/// renders it first and [`interpolate`](Self::interpolate)s after.
	const USER_CA_TOKEN: &'static str = "__SSH_USER_CA__";

	/// `script` with the user authority's token replaced by its tofu
	/// reference, `${var.ssh_user_ca}`: the last step of a `user_data`
	/// render, after its literal `${` are escaped.
	pub fn interpolate(script: &str) -> String {
		script.replace(
			Self::USER_CA_TOKEN,
			&Self::user_ca_variable().tf_var_ref(),
		)
	}
}

/// One box's identity under its stack's [`SshAuthority`]: the name its host
/// certificate is issued to, the account a login names, where its sshd
/// answers, and the two secrets its host key and certificate live in.
///
/// The host key is minted by the deploy rather than generated by the box, and
/// the box fetches it with its certificate at first boot. So its fingerprint
/// survives every rebuild, the very first connection to a new box verifies,
/// and no `known_hosts` entry ever goes stale. The key itself rides the
/// secret store, never `user_data`.
#[derive(Debug, Clone, PartialEq, Eq, Get)]
pub struct SshHost {
	/// The block label the host secrets are named for, ie `mail`.
	label: SmolStr,
	/// The name the host certificate is issued to and every connection checks
	/// it against (`HostKeyAlias`), ie `mail.beetmash.com`. An operator's
	/// `ssh ec2-user@mail.beetmash.com` verifies with no alias at all.
	name: SmolStr,
	/// The account a login names, the certificate's principal.
	user: SmolStr,
	/// The tofu output holding the address a connection dials, ie
	/// `mail_public_ip`.
	address_output: SmolStr,
	/// The port the box's own sshd answers on.
	port: u16,
}

impl SshHost {
	/// The box `label`, known as `name`, signed into as `user` on 22 at the
	/// address its stack's `address_output` holds.
	pub fn new(
		label: impl Into<SmolStr>,
		name: impl Into<SmolStr>,
		user: impl Into<SmolStr>,
		address_output: impl Into<SmolStr>,
	) -> Self {
		Self {
			label: label.into(),
			name: name.into(),
			user: user.into(),
			address_output: address_output.into(),
			port: 22,
		}
	}

	/// The box with its sshd on `port`.
	pub fn with_port(mut self, port: u16) -> Self {
		self.port = port;
		self
	}

	/// The box's host private key, ie `mail-ssh-host-key`.
	pub fn host_key_secret(&self) -> SecretRef {
		SecretRef::new(format!("{}-ssh-host-key", self.label))
	}

	/// The box's host certificate, ie `mail-ssh-host-cert`.
	pub fn host_cert_secret(&self) -> SecretRef {
		SecretRef::new(format!("{}-ssh-host-cert", self.label))
	}

	/// The two secrets the box reads at boot: its host key and certificate.
	pub fn host_secrets(&self) -> [SecretRef; 2] {
		[self.host_key_secret(), self.host_cert_secret()]
	}

	/// The [`host_secrets`](Self::host_secrets) as parameters, for the grant
	/// its runtime identity needs, ie `/beetmash/prod/mail-ssh-host-key`.
	pub fn parameter_names(&self, stack: &ResolvedStack) -> [String; 2] {
		self.host_secrets().map(|secret| stack.secret_path(&secret))
	}

	/// Where the box keeps the host key it fetched.
	pub const HOST_KEY_PATH: &'static str = "/etc/ssh/beet_host_ed25519_key";

	/// Where the box keeps the user authority it trusts.
	pub const USER_CA_PATH: &'static str = "/etc/ssh/beet_user_ca.pub";

	/// The sshd drop-in, ordered first: sshd takes the first value of each
	/// keyword it reads, so these beat the distribution's defaults.
	pub const SSHD_DROP_IN: &'static str = "/etc/ssh/sshd_config.d/00-beet.conf";

	/// The key exchanges the box's sshd offers, most preferred first, the
	/// post-quantum hybrids leading. A distribution's crypto policy can leave
	/// them out of the offer (Amazon Linux's `DEFAULT` does), and OpenSSH 10
	/// then warns on every login. The stanza keeps only the names the
	/// installed sshd supports, since an unknown one fails `sshd -t`.
	pub const KEX_ALGORITHMS: &'static [&'static str] = &[
		"mlkem768x25519-sha256",
		"sntrup761x25519-sha512",
		"sntrup761x25519-sha512@openssh.com",
		"curve25519-sha256",
		"curve25519-sha256@libssh.org",
	];

	/// The cloud-init stanza making the box's sshd trust the stack's
	/// authority and nothing else: the host key and its certificate fetched
	/// from the store (retried, since the instance's grant may land moments
	/// after it boots), the user authority written from the rendered
	/// variable, and `AuthorizedKeysFile none`, so no key in a file is a way
	/// in, whatever a provider's key pair wrote there. The same drop-in
	/// orders the key exchanges ([`KEX_ALGORITHMS`](Self::KEX_ALGORITHMS)).
	///
	/// Needs the `aws` cli holding credentials that read the two parameters
	/// ([`parameter_names`](Self::parameter_names)). Holds no `${` at all:
	/// the authority is a token the `user_data` render resolves last, with
	/// [`SshAuthority::interpolate`].
	pub fn trust_stanza(&self, stack: &ResolvedStack) -> Result<String> {
		let region = stack.aws_region()?;
		let [key_parameter, cert_parameter] = self.parameter_names(stack);
		let key_path = Self::HOST_KEY_PATH;
		let ca_path = Self::USER_CA_PATH;
		let drop_in = Self::SSHD_DROP_IN;
		let user_ca = SshAuthority::USER_CA_TOKEN;
		let kex_names = Self::KEX_ALGORITHMS.join(" ");
		format!(
			r#"
# ssh trusts the stack's certificate authority and nothing else: a login is a
# certificate its user authority signed minutes ago, and the box answers with
# the host key the deploy minted, signed by its host authority
ssh_parameter() {{
	for attempt in $(seq 1 60); do
		aws ssm get-parameter --region '{region}' --name "$1" --with-decryption --query Parameter.Value --output text && return 0
		sleep 5
	done
	echo "could not read ssh parameter $1" >&2
	return 1
}}
(umask 077 && ssh_parameter '{key_parameter}' > '{key_path}.next' && mv -f '{key_path}.next' '{key_path}')
ssh_parameter '{cert_parameter}' > '{key_path}-cert.pub.next'
mv -f '{key_path}-cert.pub.next' '{key_path}-cert.pub'
cat > '{ca_path}' <<'SSH_CA_EOF'
{user_ca}
SSH_CA_EOF
cat > '{drop_in}' <<'SSHD_EOF'
HostKey {key_path}
HostCertificate {key_path}-cert.pub
TrustedUserCAKeys {ca_path}
AuthorizedKeysFile none
SSHD_EOF
# the post-quantum key exchanges first, of the ones this sshd supports
kex=
separator=
for name in {kex_names}; do
	if ssh -Q kex | grep -qx "$name"; then
		kex="$kex$separator$name"
		separator=,
	fi
done
if [ -n "$kex" ]; then
	echo "KexAlgorithms $kex" >> '{drop_in}'
fi
sshd -t
systemctl restart sshd
"#
		)
		.xok()
	}
}

#[cfg(test)]
mod tests {
	use super::*;

	fn stack() -> ResolvedStack {
		Stack::new("beetmash")
			.with_stage("prod")
			.resolve(&PackageConfig::default())
			.with_aws_region("ap-southeast-2")
	}

	fn host() -> SshHost {
		SshHost::new(
			"mail",
			"mail.beetmash.com",
			SshAuthority::EC2_USER,
			"mail_public_ip",
		)
	}

	/// The box trusts the rendered user authority and its own certificate,
	/// and refuses every key in a file: the stanza is the whole of how a
	/// login gets in.
	#[beet_core::test]
	fn trusts_the_authority_and_no_key_file() {
		let stanza = host().trust_stanza(&stack()).unwrap();
		stanza
			.as_str()
			.xpect_contains("TrustedUserCAKeys /etc/ssh/beet_user_ca.pub")
			.xpect_contains(
				"HostCertificate /etc/ssh/beet_host_ed25519_key-cert.pub",
			)
			.xpect_contains("HostKey /etc/ssh/beet_host_ed25519_key\n")
			.xpect_contains("AuthorizedKeysFile none")
			.xpect_contains("cat > '/etc/ssh/beet_user_ca.pub' <<'SSH_CA_EOF'\n__SSH_USER_CA__\nSSH_CA_EOF")
			// the config is checked before the restart that would apply it
			.xpect_contains("sshd -t\nsystemctl restart sshd");
	}

	/// The box offers the post-quantum key exchanges first, filtered to what
	/// its sshd supports, from the drop-in that beats the distribution's
	/// crypto policy, all before the config check.
	#[beet_core::test]
	fn offers_post_quantum_key_exchange() {
		let stanza = host().trust_stanza(&stack()).unwrap();
		stanza
			.as_str()
			.xpect_contains(
				"for name in mlkem768x25519-sha256 sntrup761x25519-sha512 ",
			)
			.xpect_contains("ssh -Q kex | grep -qx \"$name\"")
			.xpect_contains(
				"echo \"KexAlgorithms $kex\" >> '/etc/ssh/sshd_config.d/00-beet.conf'",
			);
		let kex = stanza.find("KexAlgorithms").unwrap();
		(kex < stanza.find("sshd -t").unwrap()).xpect_true();
		// sorts before Amazon Linux's `50-redhat.conf`, whose crypto policy
		// would otherwise be the first value read
		(SshHost::SSHD_DROP_IN < "/etc/ssh/sshd_config.d/50-redhat.conf")
			.xpect_true();
	}

	/// The box fetches exactly its own two parameters, in the stack's
	/// region, and the key lands owner-only.
	#[beet_core::test]
	fn fetches_its_own_host_identity() {
		let stack = stack();
		let stanza = host().trust_stanza(&stack).unwrap();
		let [key, cert] = host().parameter_names(&stack);
		key.as_str().xpect_eq("/beetmash/prod/mail-ssh-host-key");
		cert.as_str().xpect_eq("/beetmash/prod/mail-ssh-host-cert");
		stanza
			.as_str()
			.xpect_contains("--region 'ap-southeast-2'")
			.xpect_contains(&format!("(umask 077 && ssh_parameter '{key}'"))
			.xpect_contains(&format!("ssh_parameter '{cert}'"));
	}

	/// The stanza survives a `user_data` escape untouched, and its one
	/// interpolation, the authority, lands only after it.
	#[beet_core::test]
	fn interpolates_only_the_authority() {
		let stanza = host().trust_stanza(&stack()).unwrap();
		stanza.as_str().xnot().xpect_contains("${");
		SshAuthority::interpolate(&stanza.replace("${", "$${"))
			.as_str()
			.xpect_contains("<<'SSH_CA_EOF'\n${var.ssh_user_ca}\nSSH_CA_EOF")
			.matches("${")
			.count()
			.xpect_eq(1);
		SshAuthority::user_ca_variable().is_content().xpect_true();
	}
}

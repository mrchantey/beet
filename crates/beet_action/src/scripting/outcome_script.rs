	#[beet_core::test]
	async fn spawns_through_the_world_api() {
		let mut world = test_world();
		run_leaf(&mut world, r#"await world.spawn({ "Name": "ada" })"#)
			.await
			.unwrap()
			.xpect_eq(Outcome::PASS);
		world
			.query::<&Name>()
			.iter(&world)
			.next()
			.unwrap()
			.as_str()
			.xpect_eq("ada");
	}

	/// The markup front-end builds the same leaf: `<RunScript>` expands to the
	/// `(Script, OutcomeScript)` pair, so a spawned template ticks.
	#[beet_core::test]
	async fn the_template_builds_a_leaf() {
		let mut world = test_world();
		let leaf = world
			.spawn_template(rsx! {
				<RunScript script={r#"await world.spawn({ "Name": "ada" });"#}/>
			})
			.unwrap()
			.id();
		world
			.entity_mut(leaf)
			.call::<(), Outcome>(())
			.await
			.unwrap()
			.xpect_eq(Outcome::PASS);
		world.query::<&Name>().iter(&world).count().xpect_eq(1);
	}

	/// The capability the whole bridge is for: the read after the write sees the

//! The behaviour-tree leaf: a script run for what it does to the world.
use crate::prelude::*;
use beet_core::prelude::*;
use core::marker::PhantomData;
use serde::Serialize;
use serde::de::DeserializeOwned;

/// Reflectable marker making a sibling [`Script`] a behaviour-tree leaf.
///
/// Installs the typed [`ScriptAction`], a default [`ScriptConfig`], and the
/// `() -> Outcome` [`ActionOverload`] a tree calls the leaf through: the script
/// runs on its default input, whatever it returned is discarded, and the leaf
/// answers [`Outcome::PASS`]. What a world-capable script *did* is already in
/// the world; a route (`ExchangeScript`) is the front-end that answers with what
/// it returned.
///
/// A component rather than a template because [`ActionOverload`] is not
/// [`Reflect`]: it has to be regenerated by a reflectable owner's `#[require]`
/// when a scene reloads. [`RunScript`] is the markup front-end that spawns the
/// pair.
///
/// A leaf, so `<Repeat>` over it is a ticking dynamic system and `<Sequence>`
/// places it in a larger behaviour.
#[derive(Component, Reflect)]
#[reflect(Component, Default)]
// `Input` and `Output` only appear in the ignored phantom marker, so an empty
// `#[reflect(where)]` drops the default bound, as on [`Script`] itself.
#[reflect(where)]
#[require(
	ScriptAction<Input, Output>,
	ScriptConfig,
	ActionOverload<(), Outcome> = outcome_overload::<Input, Output>(),
)]
pub struct OutcomeScript<Input = Value, Output = Value>
where
	Input: 'static + Send + Sync + Default + Serialize,
	Output: 'static + Send + Sync + DeserializeOwned,
{
	#[reflect(ignore)]
	_marker: PhantomData<fn() -> (Input, Output)>,
}

/// A markup-friendly scripted leaf: a `script` acting on the world through the
/// promise-shaped `world` API.
///
/// ```bsx
/// <RunScript script="
///   const [entry] = await world.entities('bevy_ecs::name::Name');
///   const name = await world.get(entry, 'bevy_ecs::name::Name');
///   const copy = await world.spawn({ 'bevy_ecs::name::Name': name + ' (copy)' });
///   await world.insert(copy, 'guestbook.Visits', 1);
/// "/>
/// ```
///
/// Every `world` method is served against the live world the moment it is
/// awaited: a read returns current state, a write lands immediately and in
/// order, a `spawn` resolves to a real entity id usable by the next line, and a
/// refused call rejects the promise where it was made, catchable in the script.
///
/// What the script is granted rides alongside as a [`ScriptConfig`] spread, so a
/// narrower leaf is composition rather than a second tag:
/// `<RunScript {ScriptConfig{read:["Name"]}} script=".."/>`, or
/// `{ScriptConfig{world:false}}` for a provably pure one.
#[template]
pub fn RunScript(
	/// The JavaScript source, an async function body evaluated with the `world`
	/// API installed.
	#[prop(into)]
	script: String,
) -> impl Bundle {
	(
		Script::<Value, Value>::new(script),
		OutcomeScript::<Value, Value>::default(),
	)
}

/// The `() -> Outcome` overload a behaviour tree calls a scripted leaf through.
///
/// Delegates to the entity's canonical [`ScriptAction`] directly rather than
/// re-entering resolution, so it can never recurse. `Sequence` and friends call
/// their children as `(), Outcome`, which is why this pair is the one a tree
/// needs.
fn outcome_overload<Input, Output>() -> ActionOverload<(), Outcome>
where
	Input: 'static + Send + Sync + Default + Serialize,
	Output: 'static + Send + Sync + DeserializeOwned,
{
	ActionOverload::new(Action::new_async_local(
		async |cx: ActionContext<()>| -> Result<Outcome> {
			let action = cx
				.caller
				.get(|action: &Action<Input, Output>| action.clone())
				.await?;
			// the leaf hands the script its default input (`Value::Null` for the
			// untyped default) and discards what it answered with.
			cx.caller
				.call_detached(action, Input::default())
				.await
				.map(|_| Outcome::PASS)
		},
	))
}

// Manual impls avoid spurious bounds on the phantom marker's types, as on
// [`Script`].
impl<Input, Output> Default for OutcomeScript<Input, Output>
where
	Input: 'static + Send + Sync + Default + Serialize,
	Output: 'static + Send + Sync + DeserializeOwned,
{
	fn default() -> Self {
		Self {
			_marker: PhantomData,
		}
	}
}

impl<Input, Output> Clone for OutcomeScript<Input, Output>
where
	Input: 'static + Send + Sync + Default + Serialize,
	Output: 'static + Send + Sync + DeserializeOwned,
{
	fn clone(&self) -> Self { Self::default() }
}

impl<Input, Output> core::fmt::Debug for OutcomeScript<Input, Output>
where
	Input: 'static + Send + Sync + Default + Serialize,
	Output: 'static + Send + Sync + DeserializeOwned,
{
	fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
		f.debug_struct("OutcomeScript").finish()
	}
}

